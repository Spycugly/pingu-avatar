const DICTS: Record<Lang, Dict> = { it, en, es, zh };

/* ---------- store: one language for every page, kept in localStorage ---------- */

const KEY = "pingu-lang";
const listeners = new Set<() => void>();

const isLang = (v: unknown): v is Lang => LANGS.some((l) => l.id === v);

/** First browser language we speak ("it-IT" → "it"), else English. Not saved: only a manual choice is. */
function detect(): Lang {
  for (const tag of navigator.languages ?? [navigator.language]) {
    const base = tag.toLowerCase().split("-")[0];
    if (isLang(base)) return base;
  }
  return "en";
}

function read(): Lang {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem(KEY);
  } catch {}
  const lang = isLang(saved) ? saved : detect();
  document.documentElement.lang = lang;
  return lang;
}

let current: Lang | null = null;

export function setLang(lang: Lang) {
  current = lang;
  try {
    localStorage.setItem(KEY, lang);
  } catch {}
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

const subscribe = (l: () => void) => {
  listeners.add(l);
  return () => listeners.delete(l);
};
const snapshot = () => (current ??= read());

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function useI18n() {
  const lang = useSyncExternalStore(subscribe, snapshot, () => "en" as Lang);
  const dict = DICTS[lang];
  const t: T = (key, vars) => {
    let s = dict[key] ?? it[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
  const locale = LANGS.find((l) => l.id === lang)!.locale;
  return { lang, t, locale, setLang };
}
